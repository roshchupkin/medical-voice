export function getLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === 'en' || stored === 'nl') return stored;
  return 'nl';
}

export function setLang(lang) {
  const next = lang === 'en' ? 'en' : 'nl';
  localStorage.setItem(STORAGE_KEY, next);
  document.documentElement.lang = next;
  for (const fn of listeners) fn(next);
}

export function toggleLang() {
  setLang(getLang() === 'nl' ? 'en' : 'nl');
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, params = {}) {
  const lang = getLang();
  let str = STRINGS[lang]?.[key] ?? STRINGS.en?.[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return str;
}

export function th(key, params = {}) {
  return t(key, params);
}

export function getDefaultTemplate() {
  return [
    { name: t('template.reasonVisit'), hint: t('template.reasonVisitHint') },
    { name: t('template.symptoms'), hint: t('template.symptomsHint') },
    { name: t('template.findings'), hint: t('template.findingsHint') },
    { name: t('template.plan'), hint: t('template.planHint') },
  ];
}

export function draftTitle() {
  const d = new Date();
  return t('draft.title', {
    date: d.toLocaleDateString(undefined, { dateStyle: 'short' }),
    time: d.toLocaleTimeString(undefined, { timeStyle: 'short' }),
  });
}

export function applyStatic(root = document) {
  document.title = t('app.title');
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.hasAttribute('data-i18n-html')) el.innerHTML = val;
    else el.textContent = val;
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  const toggle = root.getElementById('langToggleBtn');
  if (toggle) toggle.textContent = t('lang.switchTo');
}
